def _category(name: str) -> str | None:
    """Classify by name only, before any stat/open on excluded candidates."""
    parts = PurePosixPath(name).parts
    if not parts or name != PurePosixPath(name).as_posix() or any(p in {".", ".."} for p in parts) or name.startswith("/"):
        raise SnapshotError("Invalid candidate path")
    if any(p in PRIVATE_NAMES for p in parts):
        return "private-namespace"
    if parts[0] == "hosts" and name != "hosts/default.nix":
        return "machine-hosts"
    if any(p in CACHE_NAMES or p == "result" or p.startswith("result-") or p.endswith((".pyc", ".bak", ".swp", "~")) for p in parts):
        return "cache-or-backup"
    if parts[0] in METADATA_NAMESPACES or name in ROOT_METADATA:
        return "non-source-metadata"
    if name in ROOT_SOURCES or name == "hosts/default.nix" or parts[0] in SOURCE_NAMESPACES:
        return None
    raise SnapshotError("Unknown source namespace; extend the reviewed allowlist")


def _git_candidates(repo: Path) -> list[tuple[str, str]]:
    git = shutil.which("git")
    if git is None:
        raise SnapshotError("Git is required")
    # Construct a fresh environment: no inherited GIT_DIR/INDEX/WORK_TREE,
    # config injection, global hooks, credentials, tracing, or user HOME.
    with tempfile.TemporaryDirectory(prefix="envy-snapshot-git-") as isolated:
        env = {
            "PATH": os.defpath, "HOME": isolated, "XDG_CONFIG_HOME": isolated,
            "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_SYSTEM": os.devnull, "GIT_OPTIONAL_LOCKS": "0",
            "GIT_TERMINAL_PROMPT": "0", "LC_ALL": "C",
        }
        result = subprocess.run([
            git, "--no-optional-locks", "--git-dir=" + str(repo / ".git"),
            "--work-tree=" + str(repo), "-c", "core.hooksPath=" + os.devnull,
            "-c", "core.fsmonitor=false", "-c", "core.untrackedCache=false",
            "ls-files", "--cached", "--stage", "--full-name", "-z",
        ], cwd=isolated, env=env, capture_output=True, check=False)
    if result.returncode:
        # Git diagnostics may contain private paths/config values.
        raise SnapshotError("Git candidate enumeration failed")
    candidates = []
    for record in result.stdout.split(b"\0"):
        if not record:
            continue
        try:
            header, raw_name = record.split(b"\t", 1)
            mode, _oid, stage = header.decode("ascii").split()
            name = raw_name.decode("utf-8")
        except (ValueError, UnicodeError) as exc:
            raise SnapshotError("Invalid Git candidate record") from exc
        if stage != "0":
            raise SnapshotError("Unmerged Git index is unsupported")
        candidates.append((name, mode))
    if len({name for name, _ in candidates}) != len(candidates):
        raise SnapshotError("Duplicate Git candidate")
    return sorted(candidates)


def _signature(info: os.stat_result) -> tuple[int, ...]:
    return (info.st_dev, info.st_ino, info.st_mode, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


def _read_source(root_fd: int, name: str, *, expected: tuple[int, ...] | None = None) -> tuple[bytes, int] | None:
    """Open each component relative to a directory FD without following links."""
    directory = os.dup(root_fd)
    try:
        parts = PurePosixPath(name).parts
        for component in parts[:-1]:
            next_fd = os.open(component, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=directory)
            os.close(directory)
            directory = next_fd
        before = os.stat(parts[-1], dir_fd=directory, follow_symlinks=False)
        if expected is not None and _signature(before) != expected:
            raise SnapshotError("Source identity changed before read")
        if not stat.S_ISREG(before.st_mode):
            raise SnapshotError("Only regular source files are permitted")
        fd = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
        try:
            if _signature(before) != _signature(os.fstat(fd)):
                raise SnapshotError("Source replaced before read")
            chunks = []
            while chunk := os.read(fd, 1024 * 1024):
                chunks.append(chunk)
            after = os.fstat(fd)
            current = os.stat(parts[-1], dir_fd=directory, follow_symlinks=False)
            if _signature(before) != _signature(after) or _signature(before) != _signature(current):
                raise SnapshotError("Source changed during read")
            return b"".join(chunks), stat.S_IMODE(before.st_mode) & 0o777
        finally:
            os.close(fd)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise SnapshotError("Unsafe or unreadable source path") from exc
    finally:
        os.close(directory)


def _host_text(exclusions: dict[str, list[str]] | None = None) -> bytes:
    if exclusions is None:
        return b"import ../../checks/runtime/fixture.nix { }\n"
    lines = ["import ../../checks/runtime/fixture.nix {", "  exclusions = {"]
    for group, ids in sorted(exclusions.items()):
        # Nix string interpolation is rejected by the manifest validator.
        values = " ".join(json.dumps(item) for item in ids)
        lines.append(f"    {json.dumps(group)} = [ {values} ];")
    lines.extend(["  };", "}", ""])
    return "\n".join(lines).encode()


def _entry(name: str, data: bytes, mode: int, origin: str) -> dict:
    return {"relativePath": name, "mode": f"{mode:04o}", "sha256": hashlib.sha256(data).hexdigest(), "origin": origin}


def _identity(info: os.stat_result) -> tuple[int, int, int]:
    return info.st_dev, info.st_ino, info.st_mode


def _open_directory_path(path: Path) -> int:
    """Pin an absolute canonical parent without following raced ancestor links."""
    directory = os.open(path.anchor, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        for component in path.parts[1:]:
            next_fd = os.open(component, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=directory)
            os.close(directory)
            directory = next_fd
        return directory
    except BaseException:
        os.close(directory)
        raise


class _SnapshotIO:
    """Small local FD boundary shared by snapshot validation and mutation."""

    def __init__(self, root: Path, *, create: bool = False):
        try:
            # Export already canonicalized and checked this parent before Git.
            # Resolving it again could follow a link injected after that check.
            self.root = root if create else root.parent.resolve(strict=True) / root.name
            self.parent_fd = _open_directory_path(self.root.parent)
        except OSError as exc:
            raise _Conflict("Snapshot conflict opening root parent") from exc
        try:
            if create:
                os.mkdir(self.root.name, 0o700, dir_fd=self.parent_fd)
            self.fd = os.open(self.root.name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=self.parent_fd)
        except OSError as exc:
            os.close(self.parent_fd)
            raise _Conflict("Snapshot conflict opening root") from exc
        self.directories = {"": _identity(os.fstat(self.fd))}
        self.files = {}

    def __enter__(self):
        return self

    def __exit__(self, *args):
        os.close(self.fd)
        os.close(self.parent_fd)

    def check_root(self):
        parent = _open_directory_path(self.root.parent)
        try:
            if _identity(os.fstat(parent)) != _identity(os.fstat(self.parent_fd)):
                raise _Conflict("Snapshot conflict at root parent")
        finally:
            os.close(parent)
        current = os.stat(self.root.name, dir_fd=self.parent_fd, follow_symlinks=False)
        if _identity(current) != self.directories[""]:
            raise _Conflict("Snapshot conflict at root")

    def directory(self, name: str, *, create: bool = False) -> int:
        """Open components without links and remember their original identities."""
        directory = os.dup(self.fd)
        try:
            self.check_root()
            prefix = []
            for component in PurePosixPath(name).parts:
                if component in {"/", ".", ".."}:
                    raise _Conflict("Snapshot conflict at directory path")
                prefix.append(component)
                if create:
                    try:
                        os.mkdir(component, 0o700, dir_fd=directory)
                    except FileExistsError:
                        pass
                next_fd = os.open(component, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=directory)
                os.close(directory)
                directory = next_fd
                relative = "/".join(prefix)
                identity = _identity(os.fstat(directory))
                if self.directories.setdefault(relative, identity) != identity:
                    raise _Conflict("Snapshot conflict at directory identity")
            return directory
        except BaseException:
            os.close(directory)
            raise

    def read(self, name: str) -> tuple[bytes, int]:
        directory = self.directory(str(PurePosixPath(name).parent))
        try:
            before = _signature(os.stat(PurePosixPath(name).name, dir_fd=directory, follow_symlinks=False))
            if self.files.setdefault(name, before) != before:
                raise _Conflict("Snapshot conflict before read")
            result = _read_source(self.fd, name, expected=before)
            if result is None:
                raise _Conflict("Snapshot conflict at missing file")
            self.check_root()
            return result
        except (OSError, SnapshotError) as exc:
            raise _Conflict("Snapshot conflict reading file") from exc
        finally:
            os.close(directory)

    def check(self):
        """Recheck bindings without reading any newly substituted file."""
        self.check_root()
        for name in self.directories:
            os.close(self.directory(name))
        for name, expected in self.files.items():
            directory = self.directory(str(PurePosixPath(name).parent))
            try:
                current = os.stat(PurePosixPath(name).name, dir_fd=directory, follow_symlinks=False)
                if _signature(current) != expected:
                    raise _Conflict("Snapshot conflict at file identity")
            finally:
                os.close(directory)

    def replace(self, name: str, data: bytes, mode: int):
        """Stage an exclusive sibling, then recheck immediately before rename."""
        directory = self.directory(str(PurePosixPath(name).parent))
        temporary = "." + PurePosixPath(name).name + "." + os.urandom(16).hex() + ".tmp"
        try:
            fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=directory)
            try:
                with os.fdopen(os.dup(fd), "wb") as stream:
                    stream.write(data)
                os.fchmod(fd, mode)
                staged = _signature(os.fstat(fd))
                self.check()
                # Check both names on the pinned parent immediately before replace.
                if _signature(os.stat(temporary, dir_fd=directory, follow_symlinks=False)) != staged:
                    raise _Conflict("Snapshot conflict at staged file")
                if _signature(os.stat(PurePosixPath(name).name, dir_fd=directory, follow_symlinks=False)) != self.files[name]:
                    raise _Conflict("Snapshot conflict before replace")
                os.replace(temporary, PurePosixPath(name).name, src_dir_fd=directory, dst_dir_fd=directory)
                self.files[name] = _signature(os.fstat(fd))
                self.check()
            finally:
                os.close(fd)
        finally:
            os.close(directory)

    def discard(self):
        """Remove only our unchanged outputs, using the original directory FDs."""
        self.check()
        for name, expected in self.files.items():
            directory = self.directory(str(PurePosixPath(name).parent))
            try:
                if _signature(os.stat(PurePosixPath(name).name, dir_fd=directory, follow_symlinks=False)) != expected:
                    raise _Conflict("Snapshot conflict during cleanup")
                os.unlink(PurePosixPath(name).name, dir_fd=directory)
            finally:
                os.close(directory)
        for name in sorted((name for name in self.directories if name), key=lambda name: len(PurePosixPath(name).parts), reverse=True):
            directory = self.directory(str(PurePosixPath(name).parent))
            try:
                os.rmdir(PurePosixPath(name).name, dir_fd=directory)
            finally:
                os.close(directory)
        self.check_root()
        os.rmdir(self.root.name, dir_fd=self.parent_fd)


def _put(root: _SnapshotIO, name: str, data: bytes, mode: int) -> None:
    directory = root.directory(str(PurePosixPath(name).parent), create=True)
    try:
        fd = os.open(PurePosixPath(name).name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=directory)
        try:
            with os.fdopen(os.dup(fd), "wb") as stream:
                stream.write(data)
            os.fchmod(fd, mode)
            root.files[name] = _signature(os.fstat(fd))
        finally:
            os.close(fd)
        root.check_root()
        if _signature(os.stat(PurePosixPath(name).name, dir_fd=directory, follow_symlinks=False)) != root.files[name]:
            raise _Conflict("Snapshot conflict after create")
    finally:
        os.close(directory)


def _manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()


def _write_manifest(root: _SnapshotIO, manifest: dict) -> None:
    _put(root, MANIFEST_NAME, _manifest_bytes(manifest), 0o600)


def export_snapshot(repo: Path | str, destination: Path | str) -> dict:
    """Copy tracked/ITA current bytes into a new directory; never write the repo."""
    repo = Path(repo).absolute()
    destination = Path(destination).absolute()
    if repo.is_symlink() or not (repo / ".git").is_dir() or (repo / ".git").is_symlink():
        raise SnapshotError("A regular checkout with its own Git directory is required")
    repo = repo.resolve(strict=True)
    parent = destination.parent.resolve(strict=True)
    destination = parent / destination.name
    if destination == repo or repo in destination.parents or destination.exists() or destination.is_symlink():
        raise SnapshotError("Destination must be a new directory outside the source checkout")
    candidates = _git_candidates(repo)
    excluded = {category: 0 for category in ("private-namespace", "machine-hosts", "cache-or-backup", "non-source-metadata", "deleted-source")}
    allowed = []
    for name, mode in candidates:
        category = _category(name)
        if category:
            excluded[category] += 1
        elif mode not in {"100644", "100755"}:
            raise SnapshotError("Symlinks and submodules are unsupported")
        else:
            allowed.append(name)
    with _SnapshotIO(destination, create=True) as output:
        root_fd = os.open(repo, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            entries = []
            for name in allowed:
                result = _read_source(root_fd, name)
                if result is None:
                    excluded["deleted-source"] += 1
                    continue
                data, mode = result
                if name == "hosts/default.nix":
                    clean = re.sub(r"#[^\n]*", "", data.decode("utf-8"))
                    if re.fullmatch(r"\s*\{\s*\.\.\.\s*}\s*:\s*\{\s*}\s*", clean) is None:
                        raise SnapshotError("Shared host defaults are no longer empty")
                _put(output, name, data, mode)
                entries.append(_entry(name, data, mode, "working-tree"))
            names = {entry["relativePath"] for entry in entries}
            if not ROOT_SOURCES.issubset(names) or "checks/runtime/fixture.nix" not in names:
                raise SnapshotError("Snapshot is missing a required source entry")
            for directory in ("hosts/linux", "hosts/darwin"):
                os.close(output.directory(directory, create=True))
            for name, data, mode in ((MIN_HOST, _host_text(), 0o644), (DEFAULT_HOST, _host_text(), 0o644), (SEED_SCRIPT, GUEST_SEED_SCRIPT.encode(), 0o755)):
                _put(output, name, data, mode)
                entries.append(_entry(name, data, mode, "synthetic"))
            manifest = {
                "schemaVersion": 1,
                "files": sorted(entries, key=lambda entry: entry["relativePath"]),
                "lockSha256": next(entry["sha256"] for entry in entries if entry["relativePath"] == "flake.lock"),
                "excludedCategories": excluded,
                "fixture": {"minimalHost": "runtime-min", "defaultHost": "runtime-default", "selectionStage": "initial", "secrets": "guest-generated-only"},
            }
            _write_manifest(output, manifest)
            _verify_snapshot(output)
            return manifest
        except _Conflict:
            raise
        except OSError as exc:
            raise _Conflict("Snapshot conflict during export") from exc
        except BaseException:
            output.discard()
            raise
        finally:
            os.close(root_fd)


def _verify_snapshot(root: _SnapshotIO) -> dict:
    manifest = json.loads(root.read(MANIFEST_NAME)[0])
    if manifest.get("schemaVersion") != 1:
        raise SnapshotError("Unsupported snapshot manifest")
    entries = manifest["files"]
    expected = {entry["relativePath"] for entry in entries}
    if len(expected) != len(entries):
        raise SnapshotError("Duplicate manifest path")
    for name in expected:
        if name not in GENERATED_PATHS and _category(name) is not None:
            raise SnapshotError("Snapshot contains an excluded path")
    actual = set()

    def inventory(directory: int, prefix: str = ""):
        for name in os.listdir(directory):
            relative = prefix + name
            info = os.stat(name, dir_fd=directory, follow_symlinks=False)
            if stat.S_ISLNK(info.st_mode):
                raise _Conflict("Snapshot conflict at symlink")
            if stat.S_ISDIR(info.st_mode):
                if not any(item.startswith(relative + "/") for item in expected) and relative != "hosts/darwin":
                    raise SnapshotError("Unexpected snapshot directory")
                child = root.directory(relative)
                try:
                    inventory(child, relative + "/")
                finally:
                    os.close(child)
            elif not stat.S_ISREG(info.st_mode):
                raise SnapshotError("Snapshot contains a non-regular file")
            elif relative != MANIFEST_NAME:
                if relative not in GENERATED_PATHS and _category(relative) is not None:
                    raise SnapshotError("Snapshot contains an excluded path")
                actual.add(relative)

    inventory(root.fd)
    if actual != expected:
        raise SnapshotError("Snapshot inventory differs from manifest")
    for entry in entries:
        result = root.read(entry["relativePath"])
        if _entry(entry["relativePath"], *result, entry["origin"]) != entry:
            raise SnapshotError("Snapshot content or mode differs from manifest")
    lock = next((entry["sha256"] for entry in entries if entry["relativePath"] == "flake.lock"), None)
    if lock is None or lock != manifest["lockSha256"]:
        raise SnapshotError("Snapshot lock digest mismatch")
    root.check()
    return manifest


def verify_snapshot(root: Path | str) -> dict:
    """Check inventory and contents through one pinned no-follow root FD."""
    try:
        with _SnapshotIO(Path(root)) as source:
            return _verify_snapshot(source)
    except OSError as exc:
        raise _Conflict("Snapshot conflict during verification") from exc


def minimal_exclusions(evaluated_manifest: dict) -> dict[str, list[str]]:
    """Derive literal exclusions from a synthetic host's evaluated effective IDs."""
    if evaluated_manifest.get("schemaVersion") != 3 or evaluated_manifest.get("id") != "runtime-min" or evaluated_manifest.get("platform") != "linux":
        raise SnapshotError("Expected the initial synthetic runtime-min manifest v3")
    settings = evaluated_manifest.get("settings", {})
    if any(settings.get(key) != value for key, value in {
        "envy.user.name": "envy-runtime", "envy.user.home": "/home/envy-runtime",
        "envy.repository.path": "/home/envy-runtime/.envy", "envy.linux.option": "server",
        "envy.linux.desktop": "none", "envy.mirrors.mode": "upstream",
        "envy.storage.mode": "manual", "envy.storage.archive.repository": "",
    }.items()):
        raise SnapshotError("Manifest does not describe the synthetic fixture")
    groups = evaluated_manifest.get("software", {}).get("groups", {})
    if set(groups) != set(GROUP_OPTIONS):
        raise SnapshotError("Unexpected software groups; review fixture selection")
    exclusions = {}
    for name, option in GROUP_OPTIONS.items():
        group = groups[name]
        selection = group.get("selection", {})
        if group.get("optionPath") != option or selection.get("exclude") != []:
            raise SnapshotError("Expected initial direct selection with no exclusions")
        effective = selection.get("effective")
        included = selection.get("include")
        if not isinstance(effective, list) or not isinstance(included, list) or any(item not in included for item in effective) or any(item not in effective for item in included):
            raise SnapshotError("Expected complete initial include/effective inventories")
        ids = []
        for item in effective:
            if not isinstance(item, dict):
                raise SnapshotError("Invalid effective item")
            item_id = item.get("id")
            reference = item.get("ref")
            # Dynamic native packages have stable IDs but may lack a canonical ref.
            # Excluding an evaluated ID does not create or invent a source reference.
            valid_reference = (isinstance(reference, str) and bool(reference)) or (
                name == "native.system.package" and "ref" in item and reference is None
            )
            if not isinstance(item_id, str) or re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9@+._/-]*", item_id) is None or not valid_reference:
                raise SnapshotError("Effective item lacks a safe ID or verified reference")
            ids.append(item_id)
        if len(set(ids)) != len(ids):
            raise SnapshotError("Duplicate effective item ID")
        if name == "nix.user.package" and not REQUIRED_NIX_IDS.issubset(ids):
            raise SnapshotError("Required lifecycle tools are missing from the evaluated manifest")
        exclusions[name] = sorted(set(ids) - (MINIMAL_NIX_IDS if name == "nix.user.package" else set()))
    return exclusions


def apply_minimal_selection(root: Path | str, evaluated_manifest: dict) -> dict:
    """Patch only the new exported runtime-min host after initial evaluation."""
    exclusions = minimal_exclusions(evaluated_manifest)
    try:
        with _SnapshotIO(Path(root)) as source:
            manifest = _verify_snapshot(source)
            if manifest["fixture"]["selectionStage"] != "initial" or source.read(MIN_HOST)[0] != _host_text():
                raise SnapshotError("Minimal fixture selection has already changed")
            data = _host_text(exclusions)
            source.replace(MIN_HOST, data, 0o644)
            manifest["files"] = [(_entry(MIN_HOST, data, 0o644, "synthetic") if entry["relativePath"] == MIN_HOST else entry) for entry in manifest["files"]]
            manifest["fixture"]["selectionStage"] = "minimal"
            manifest["fixture"]["exclusions"] = exclusions
            source.replace(MANIFEST_NAME, _manifest_bytes(manifest), 0o600)
            return _verify_snapshot(source)
    except OSError as exc:
        raise _Conflict("Snapshot conflict during selection") from exc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    export = commands.add_parser("export")
    export.add_argument("repo", type=Path)
    export.add_argument("destination", type=Path)
    verify = commands.add_parser("verify")
    verify.add_argument("snapshot", type=Path)
    select = commands.add_parser("select-minimal")
    select.add_argument("snapshot", type=Path)
    select.add_argument("evaluated_manifest", type=Path)
    args = parser.parse_args()
    try:
        if args.command == "export":
            result = export_snapshot(args.repo, args.destination)
        elif args.command == "verify":
            result = verify_snapshot(args.snapshot)
        else:
            result = apply_minimal_selection(args.snapshot, json.loads(args.evaluated_manifest.read_text()))
    except (SnapshotError, OSError, ValueError, KeyError) as exc:
        # Do not echo exception details that may include source paths or values.
        parser.exit(1, f"Snapshot operation failed ({type(exc).__name__}).\n")
    print(json.dumps({"schemaVersion": 1, "fileCount": len(result["files"]), "lockSha256": result["lockSha256"], "selectionStage": result["fixture"]["selectionStage"]}, sort_keys=True))


if __name__ == "__main__":
    main()
